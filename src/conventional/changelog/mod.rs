use crate::conventional::changelog::error::ChangelogError;

use std::fs;
use std::path::Path;

pub mod error;
pub(crate) mod release;
pub(crate) mod renderer;
pub(crate) mod serde;
pub mod template;

pub use renderer::Renderer;

const CHANGELOG_SEPARATOR: &str = "- - -";

const DEFAULT_CONTENT: &str = "# Changelog
All notable changes to this project will be documented in this file. \
See [conventional commits](https://www.conventionalcommits.org/) for commit guidelines.

- - -
Changelog generated by [cocogitto](https://github.com/cocogitto/cocogitto).";

pub struct RenderOutput(pub String);

impl RenderOutput {
    pub fn write_to_file(&self, path: impl AsRef<Path>) -> Result<(), ChangelogError> {
        let mut changelog_content =
            fs::read_to_string(path.as_ref()).unwrap_or_else(|_| DEFAULT_CONTENT.to_string());

        let Some(idx) = changelog_content.find(CHANGELOG_SEPARATOR) else {
            return Err(ChangelogError::SeparatorNotFound(
                path.as_ref().to_path_buf(),
            ));
        };

        changelog_content.insert(idx + CHANGELOG_SEPARATOR.len(), '\n');
        changelog_content.insert_str(idx + CHANGELOG_SEPARATOR.len() + 1, &self.0);
        changelog_content.insert_str(
            idx + CHANGELOG_SEPARATOR.len() + 1 + self.0.len(),
            "\n- - -\n",
        );
        fs::write(path.as_ref(), changelog_content)?;

        Ok(())
    }
}
